package com.elabboubisolution.madconverter.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Shared spacing, on Material 3's 4dp grid. One 16dp edge everywhere (screen, sheets, cards,
 * list rows) so text lines up with the top bar title and the Material list items.
 */
object Dimens {
    /** Horizontal edge of the screen and of every bottom sheet. Matches the top bar and ListItem. */
    val EdgePadding = 16.dp

    /** Padding inside cards. */
    val CardPadding = 16.dp

    /** Vertical gap between the screen's sections. */
    val SectionSpacing = 16.dp
}
